// public.h
// Shared IOCTL/struct definitions between GmuxDriver.sys and the usermode
// client (gmux.cpp). Included by both.

#pragma once

#define IOCTL_GMUX_READ8     CTL_CODE(FILE_DEVICE_UNKNOWN, 0x800, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_GMUX_WRITE8    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_GMUX_SWITCH_TO CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_ANY_ACCESS)
// Granular building blocks so the client can insert PnP steps between them:
//   ROUTE          - DDC (port 0x28), panel route (port 0x10) and external DP mux (port
//                    0x40), written in that order like Linux gmux_switchto()
//                    (GMUX_SWITCH_REQUEST/RESPONSE, TargetIsDiscrete). The external mux is
//                    forced to the dGPU unless Parameters\ExternalFollowsPanel is set (Linux
//                    does the same on Thunderbolt Macs). Success reflects the panel write; a
//                    failed DDC / external write is only logged.
//   POWER          - dGPU power rail only (GMUX_POWER_REQUEST/RESPONSE)
//   ROUTE_EXTERNAL - external DP mux only (port 0x40), same request/response as ROUTE
#define IOCTL_GMUX_ROUTE     CTL_CODE(FILE_DEVICE_UNKNOWN, 0x803, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_GMUX_POWER     CTL_CODE(FILE_DEVICE_UNKNOWN, 0x804, METHOD_BUFFERED, FILE_ANY_ACCESS)
// Boot default. The driver keeps the panel route in
//   HKLM\SYSTEM\CurrentControlSet\Services\<service>\Parameters\DefaultRoute
// and re-applies it every time the gmux device starts (= every Windows boot).
//   SET_DEFAULT   - read the CURRENT panel route from the hardware (port 0x10 bit 0) and
//                   store it as the default
//   GET_DEFAULT   - report the stored default (Route 0 = none stored)
//   CLEAR_DEFAULT - delete the stored default
#define IOCTL_GMUX_SET_DEFAULT   CTL_CODE(FILE_DEVICE_UNKNOWN, 0x805, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_GMUX_GET_DEFAULT   CTL_CODE(FILE_DEVICE_UNKNOWN, 0x806, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_GMUX_CLEAR_DEFAULT CTL_CODE(FILE_DEVICE_UNKNOWN, 0x807, METHOD_BUFFERED, FILE_ANY_ACCESS)
// Panel backlight. On dual-GPU T2 Macs the panel PWM is generated by the gmux (TI LP8548 behind
// the T2 SMC), not by the iGPU/dGPU - Linux exposes it as /sys/class/backlight/gmux_backlight.
//   BL_GET - gmux port 0x74 (current, 24 bit) and port 0x70 (max, 65535 on MBP16,1); both are
//            32-bit BIG-endian values on the T2 MMIO gmux (read cmd 0x04, write cmd 0x44).
//   BL_SET - writes port 0x74. Value is clamped to Max when Max is known.
#define IOCTL_GMUX_BL_GET        CTL_CODE(FILE_DEVICE_UNKNOWN, 0x809, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_GMUX_BL_SET        CTL_CODE(FILE_DEVICE_UNKNOWN, 0x80A, METHOD_BUFFERED, FILE_ANY_ACCESS)

// External DP mux only (for testing one thing at a time; ROUTE already covers both muxes).
#define IOCTL_GMUX_ROUTE_EXTERNAL CTL_CODE(FILE_DEVICE_UNKNOWN, 0x808, METHOD_BUFFERED, FILE_ANY_ACCESS)

// Route values as WRITTEN to ports 0x10 (panel) and 0x40 (external). They are also what this
// project stores as the boot default. Readback is different: the panel route is read from
// port 0x10 bit 0 (1 = dGPU, 0 = iGPU); port 0x11 gives 3 / 0 on T2. Port 0x41 is NOT a route
// indicator (it read 0x10 with the panel on the dGPU after any write to 0x40).
#define GMUX_ROUTE_IGD   2
#define GMUX_ROUTE_DGPU  3

// DDC/AUX line (port 0x28) uses its own numbering: 1 = iGPU, 2 = dGPU.
#define GMUX_DDC_IGD     1
#define GMUX_DDC_DGPU    2

typedef struct _GMUX_READ_REQUEST {
    UCHAR Port;
} GMUX_READ_REQUEST, *PGMUX_READ_REQUEST;

typedef struct _GMUX_READ_RESPONSE {
    UCHAR   Value;
    BOOLEAN Success;
} GMUX_READ_RESPONSE, *PGMUX_READ_RESPONSE;

typedef struct _GMUX_WRITE_REQUEST {
    UCHAR Port;
    UCHAR Value;
} GMUX_WRITE_REQUEST, *PGMUX_WRITE_REQUEST;

typedef struct _GMUX_WRITE_RESPONSE {
    BOOLEAN Success;
} GMUX_WRITE_RESPONSE, *PGMUX_WRITE_RESPONSE;

// TargetIsDiscrete: 0 = switch to iGPU, 1 = switch to dGPU
typedef struct _GMUX_SWITCH_REQUEST {
    UCHAR TargetIsDiscrete;
} GMUX_SWITCH_REQUEST, *PGMUX_SWITCH_REQUEST;

typedef struct _GMUX_SWITCH_RESPONSE {
    BOOLEAN Success;
} GMUX_SWITCH_RESPONSE, *PGMUX_SWITCH_RESPONSE;

// PowerOn: 0 = dGPU rail off, 1 = dGPU rail on
typedef struct _GMUX_POWER_REQUEST {
    UCHAR PowerOn;
} GMUX_POWER_REQUEST, *PGMUX_POWER_REQUEST;

typedef struct _GMUX_POWER_RESPONSE {
    BOOLEAN Success;
} GMUX_POWER_RESPONSE, *PGMUX_POWER_RESPONSE;

typedef struct _GMUX_BL_GET_RESPONSE {
    ULONG   Value;
    ULONG   Max;       // 0 if port 0x70 could not be read
    BOOLEAN Success;
} GMUX_BL_GET_RESPONSE, *PGMUX_BL_GET_RESPONSE;

typedef struct _GMUX_BL_SET_REQUEST {
    ULONG Value;
} GMUX_BL_SET_REQUEST, *PGMUX_BL_SET_REQUEST;

typedef struct _GMUX_BL_SET_RESPONSE {
    BOOLEAN Success;
} GMUX_BL_SET_RESPONSE, *PGMUX_BL_SET_RESPONSE;

// Route: 0 = no default stored, GMUX_ROUTE_IGD or GMUX_ROUTE_DGPU otherwise
typedef struct _GMUX_DEFAULT_RESPONSE {
    UCHAR   Route;
    BOOLEAN Success;
} GMUX_DEFAULT_RESPONSE, *PGMUX_DEFAULT_RESPONSE;

// Full gmux port map, from Linux include/linux/apple-gmux.h
#define GMUX_PORT_VERSION_MAJOR    0x04
#define GMUX_PORT_VERSION_MINOR    0x05
#define GMUX_PORT_VERSION_RELEASE  0x06
#define GMUX_PORT_SWITCH_DISPLAY   0x10   // panel route: 2 = iGPU, 3 = dGPU
#define GMUX_PORT_SWITCH_GET_DISPLAY 0x11  // informational only: 3 = dGPU, 0 = iGPU on T2 (Linux reads 0x10 bit 0)
#define GMUX_PORT_INTERRUPT_ENABLE  0x14
#define GMUX_PORT_INTERRUPT_STATUS  0x16
#define GMUX_PORT_SWITCH_DDC       0x28   // panel DDC: 1 = iGPU, 2 = dGPU. Linux writes it; on this T2 gmux it reads 0 before and after
#define GMUX_PORT_SWITCH_EXTERNAL  0x40   // external DP mux: 2 = iGPU, 3 = dGPU (separate from the panel mux)
#define GMUX_PORT_SWITCH_GET_EXTERNAL 0x41  // informational only: not a route indicator on T2 (0x00 at boot, 0x10 after writing 0x40)
#define GMUX_PORT_DISCRETE_POWER  0x50   // dGPU power rail sequencing
#define GMUX_PORT_MAX_BRIGHTNESS  0x70
#define GMUX_PORT_BRIGHTNESS      0x74
#define GMUX_BRIGHTNESS_MASK      0x00FFFFFFUL